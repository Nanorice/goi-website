const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const originalTitle = document.title;

function translatedText(value, language) {
  const trimmed = value.trim();
  const translation = chineseTranslations.get(trimmed.replace(/\s+/g, ' '));
  if (!translation) return value;
  const start = value.indexOf(trimmed);
  return `${value.slice(0, start)}${language === 'zh-CN' ? translation : trimmed}${value.slice(start + trimmed.length)}`;
}

function setLanguage(language) {
  const useChinese = language === 'zh-CN';
  document.documentElement.lang = useChinese ? 'zh-CN' : 'en';
  document.title = translatedText(originalTitle, language);

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    node.nodeValue = translatedText(originalText.get(node), language);
  }

  document.querySelectorAll('[alt], [aria-label], [placeholder], [title]').forEach(element => {
    ['alt', 'aria-label', 'placeholder', 'title'].forEach(attribute => {
      if (!element.hasAttribute(attribute)) return;
      let values = originalAttributes.get(element);
      if (!values) {
        values = {};
        originalAttributes.set(element, values);
      }
      if (!(attribute in values)) values[attribute] = element.getAttribute(attribute);
      element.setAttribute(attribute, translatedText(values[attribute], language));
    });
  });

  const description = document.querySelector('meta[name="description"]');
  if (description) {
    if (!originalAttributes.has(description)) originalAttributes.set(description, {});
    const values = originalAttributes.get(description);
    if (!('content' in values)) values.content = description.content;
    description.content = translatedText(values.content, language);
  }

  if (menuBtn) menuBtn.setAttribute('aria-label', useChinese ? '菜单' : 'Menu');
  languageButton.textContent = useChinese ? 'English' : '中文';
  languageButton.setAttribute('aria-label', useChinese ? '切换为英文' : 'Switch to Chinese');
  languageButton.setAttribute('aria-pressed', String(useChinese));
}

if (navContainer) {
  navContainer.append(languageButton);
  setLanguage(localStorage.getItem('golden-ocean-language') || 'en');
}

function submitQuote(e) {
  e.preventDefault();
  const f = new FormData(e.target);
  const useChinese = document.documentElement.lang === 'zh-CN';
  const subject = encodeURIComponent(
    useChinese ? 'Golden Ocean 网站咨询 — ' + (f.get('product') || '一般咨询') : 'Golden Ocean website enquiry — ' + (f.get('product') || 'General')
  );
  const body = encodeURIComponent([
    `${useChinese ? '姓名' : 'Name'}: ${f.get('name') || ''}`,
    `${useChinese ? '公司' : 'Company'}: ${f.get('company') || ''}`,
    `${useChinese ? '电子邮箱' : 'Email'}: ${f.get('email') || ''}`,
    `${useChinese ? '电话' : 'Phone'}: ${f.get('phone') || ''}`,
    `${useChinese ? '产品' : 'Product'}: ${f.get('product') || ''}`,
    `${useChinese ? '省份' : 'Province'}: ${f.get('province') || ''}`,
    `${useChinese ? '预估数量' : 'Approx. quantity'}: ${f.get('quantity') || ''}`,
    '',
    f.get('message') || ''
  ].join('\n'));
  window.location.href = `mailto:goldenoceancanada@gmail.com?subject=${subject}&body=${body}`;
}
